from django.core.management.base import BaseCommand
from django.db.models import Subquery

from news.models import Article, Summary


class Command(BaseCommand):
    help = "Print the SQL generated by the JOIN and SUBQUERY implementations."

    def handle(self, *args, **options):
        join_query = (
            Article.objects
            .select_related('outlet', 'category')
            .order_by('-published_at')
        )
        self.stdout.write(self.style.MIGRATE_HEADING(
            "JOIN - Article + Outlet + Category"
        ))
        self.stdout.write(str(join_query.query))
        self.stdout.write("")

        summary_article_ids = Summary.objects.values('article_id')
        subquery = (
            Article.objects
            .filter(id__in=Subquery(summary_article_ids))
            .select_related('outlet', 'category')
            .order_by('-published_at')
        )
        self.stdout.write(self.style.MIGRATE_HEADING(
            "SUBQUERY - Articles that have an AI summary"
        ))
        self.stdout.write(str(subquery.query))
